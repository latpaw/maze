  function bounds(part) {
    if (part.type === 'ellipse') return [part.x - part.rx, part.y - part.ry, part.x + part.rx, part.y + part.ry];
    if (part.type === 'rect') return [part.x, part.y, part.x + part.w, part.y + part.h];
    return [Math.min(...part.points.map(p => p[0])), Math.min(...part.points.map(p => p[1])), Math.max(...part.points.map(p => p[0])), Math.max(...part.points.map(p => p[1]))];
  }
  function inside(part, x, y) {
    if (part.type === 'ellipse') return ((x - part.x) / part.rx) ** 2 + ((y - part.y) / part.ry) ** 2 <= 1;
    if (part.type === 'rect') return x >= part.x && x <= part.x + part.w && y >= part.y && y <= part.y + part.h;
    let hit = false;
    const a = part.points;
    for (let i = 0, j = a.length - 1; i < a.length; j = i++) {
      if ((a[i][1] > y) !== (a[j][1] > y) && x < (a[j][0] - a[i][0]) * (y - a[i][1]) / (a[j][1] - a[i][1]) + a[i][0]) hit = !hit;
    }
    return hit;
  }
